/**
 * Generate version.ts from package.json
 * Run before bundling so the version is baked into compiled binaries.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const pkgPath = join(import.meta.dir, "../package.json");
const pkg = JSON.parse(readFileSync(pkgPath, "utf-8"));
const version = pkg.version;

// #1140 — the image's git revision, fed by the Dockerfile's
// CLAUDISH_REVISION build arg (compose build.args from `git rev-parse HEAD`).
// VERSION cannot tell two fleet images apart: the fork deploys through
// `docker compose build`, never a release bump, so VERSION has read "7.1.2"
// since 2026-05 while a thousand commits shipped. REVISION names the BUILD.
// "unknown" = built outside the docker path (local dev, compiled binaries).
const revision = process.env.CLAUDISH_REVISION || "unknown";

const outPath = join(import.meta.dir, "../src/version.ts");
writeFileSync(
  outPath,
  `// Auto-generated by scripts/generate-version.ts — do not edit\nexport const VERSION = "${version}";\nexport const REVISION = "${revision}";\n`
);

console.log(`[generate-version] ${version} (${revision}) → src/version.ts`);
